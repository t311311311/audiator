// The stored choice wins; otherwise follow the OS language, falling back to
// English for anything we do not ship.
function resolveLanguage(stored, osLocale) {
  if (stored && STRINGS[stored]) return stored;
  const l = String(osLocale || '').toLowerCase();
  if (l.startsWith('ru')) return 'ru';
  if (l.startsWith('zh')) return 'zh';
  return FALLBACK;
}

// Full string table for a language, English filling any gaps.
function stringsFor(lang) {
  return { ...STRINGS[FALLBACK], ...(STRINGS[lang] || {}) };
}

function t(lang, key) {
  const table = stringsFor(lang);
  return table[key] !== undefined ? table[key] : key;
}

// A length of time in words: "1 ч 23 мин", "2 ч", "45 мин" (the main
// process; the pages keep the same few lines of their own).
function duration(lang, seconds) {
  const m = Math.floor(seconds / 60), h = Math.floor(m / 60);
  const H = t(lang, 'unit.h'), M = t(lang, 'unit.min');
  if (!h) return `${m} ${M}`;
  return m % 60 ? `${h} ${H} ${m % 60} ${M}` : `${h} ${H}`;
}

module.exports = { LANGUAGES, FALLBACK, STRINGS, resolveLanguage, stringsFor, t, duration };
